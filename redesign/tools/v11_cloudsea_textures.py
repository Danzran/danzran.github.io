# Build the page textures from the Codex PNGs: brush webps, cloud atlas (4x2 cells of 512, greyscale), peaks webp
import sys, os
from PIL import Image, ImageOps, ImageFilter
G = sys.argv[1]
def P(n): return os.path.join(G, n)
for n in ('brush-a', 'brush-b'):
    if os.path.exists(P(n + '.png')):
        im = Image.open(P(n + '.png')).convert('L')
        im.save(P(n + '.webp'), quality=88)
sheets = [n for n in sys.argv[2].split(',') if os.path.exists(P(n + '.png'))]
cells = []
for n in sheets:
    im = Image.open(P(n + '.png')).convert('L').resize((1024, 1024), Image.LANCZOS)
    for cy in range(2):
        for cx in range(2):
            c = im.crop((cx * 512, cy * 512, cx * 512 + 512, cy * 512 + 512))
            # kill the faint black-level noise and fade the cell border so nothing bleeds between cells
            c = c.point(lambda v: 0 if v < 10 else v)
            m = Image.new('L', (512, 512), 0); m.paste(255, (14, 14, 498, 498)); m = m.filter(ImageFilter.GaussianBlur(8))
            c = Image.composite(c, Image.new('L', (512, 512), 0), m)
            cells.append(c)
while len(cells) < 8: cells.append(cells[len(cells) % max(1, len(cells))])
atlas = Image.new('L', (2048, 1024))
for i, c in enumerate(cells[:8]): atlas.paste(c, ((i % 4) * 512, (i // 4) * 512))
atlas.save(P('cloud-atlas.webp'), quality=86)
if os.path.exists(P('peaks-a.png')):
    Image.open(P('peaks-a.png')).convert('L').resize((2048, 640), Image.LANCZOS).save(P('peaks.webp'), quality=86)
print('ok', sheets)
# file:// pages cannot upload file images to WebGL or read them back from a canvas (they count as cross-origin),
# so every texture the page reads pixels from is also embedded as a data URI in textures.js
import base64, io
def b64(path):
    return 'data:image/webp;base64,' + base64.b64encode(open(path, 'rb').read()).decode()
fig_src = sys.argv[3]
fig = Image.open(fig_src).convert('RGBA'); fig = fig.resize((round(fig.width * 760 / fig.height), 760), Image.LANCZOS)
fig.save(P('figure.webp'), quality=90)
for n in ('brush-a', 'brush-b'):
    if os.path.exists(P(n + '.png')): Image.open(P(n + '.png')).convert('L').save(P(n + '.webp'), lossless=True)
tex = {'atlas': 'cloud-atlas.webp', 'peaks': 'peaks.webp', 'fig': 'figure.webp', 'brushA': 'brush-a.webp', 'brushB': 'brush-b.webp'}
with open(P('../textures.js'), 'w') as f:
    f.write('/* v11 Cloud Sea textures as data URIs (generated by the asset build from assets/gen/*.webp), so WebGL and canvas\n   can read their pixels when the page is opened over file://. Sources and prompts: PROMPTS.md. */\nwindow.SEA_TEX = {\n')
    for k, v in tex.items():
        if os.path.exists(P(v)): f.write(f'  {k}: "{b64(P(v))}",\n')
    f.write('};\n')
print('textures.js written')
