"""Precompute overlay data for the project plates (redesign/assets/projects/*/plate.webp) -> data.js.
Canvas getImageData is blocked over file://, so pixel-derived data (corners, digit grid) is baked here.
Run with the Windows python (cv2): python projects_data.py <assets/projects dir>"""
import sys, json, cv2, numpy as np
A = sys.argv[1]
out = {}
# flow: Shi-Tomasi corners, the same detector the KLT tracker seeds from
im = cv2.imread(f"{A}/flow/plate.webp"); g = cv2.cvtColor(im, cv2.COLOR_BGR2GRAY); H, W = g.shape
c = cv2.goodFeaturesToTrack(g, maxCorners=170, qualityLevel=.03, minDistance=34, blockSize=9).reshape(-1, 2)
out['flow'] = {'corners': [[round(float(x) / W, 4), round(float(y) / H, 4)] for x, y in c]}
# digits: the hand-drawn 7 cropped square and resampled to MNIST's 28x28, ink = high values
im = cv2.imread(f"{A}/digits/plate.webp", 0); H, W = im.shape
ink = 255 - im
ink[int(.76 * H):, int(.46 * W):] = 0          # the marker nib reaches into the square; keep only the digit
x0, y0, s = int(.03 * W), int(.12 * H), int(.80 * H)
crop = ink[y0:y0 + s, x0:x0 + s]
crop = np.clip((crop.astype(float) - 90) * 1.8, 0, 255)
small = cv2.resize(crop, (28, 28), interpolation=cv2.INTER_AREA)
out['digits'] = {'crop': [x0 / W, y0 / H, s / W, s / H], 'grid': [[int(v) for v in row] for row in small]}
open(f"{A}/data.js", 'w').write('/* generated by redesign/tools/projects_data.py */\nwindow.PROJECT_DATA = ' + json.dumps(out, separators=(',', ':')) + ';\n')
print(len(c), 'corners')
for row in small[::2]: print(''.join('#' if v > 120 else '.' for v in row))
